class AlphabetTeacher:
    @staticmethod
    def all():
        return "\n".join(f"{u} {l} - {n}" for u, l, n in ARM_ALPHABET_LIST)

    @staticmethod
    def random_letter():
        u, l, n = random.choice(ARM_ALPHABET_LIST)
        return f"{u} {l} - {n}"

class NumberTeacher:
    @staticmethod
    def to_arm(n: int) -> str:
        if n < 0:
            return "minus " + NumberTeacher.to_arm(-n)
        if n < 20:
            for v, w in ARM_NUMBERS:
                if v == n:
                    return w
        if n < 100:
            tens = (n // 10) * 10
            rest = n % 10
            base = dict(ARM_NUMBERS)[tens]
            if rest == 0:
                return base
            unit = dict(ARM_NUMBERS)[rest]
            if unit.endswith("ը"):
                unit = unit[:-1]
            return base + unit
        if n < 1000:
            h = n // 100
            rest = n % 100
            hw = dict(ARM_NUMBERS)[h]
            if rest == 0:
                return hw + "հարյուր"
            return hw + "հարյուր " + NumberTeacher.to_arm(rest)
        if n == 1000:
            return "հազար"
        if n < 1000000:
            th = n // 1000
            rest = n % 1000
            tw = NumberTeacher.to_arm(th)
            if rest == 0:
                return tw + " հազար"
            return tw + " հազար " + NumberTeacher.to_arm(rest)
        return str(n)

class DateInfo:
    @staticmethod
    def today():
        now = datetime.datetime.now()
        dw = dict(ARM_DAYS)[now.isoweekday()]
        m = dict(ARM_MONTHS)[now.month]
        return f"Այսօր՝ {dw}, {now.day} {m} {now.year} թ."

class Search:
    @staticmethod
    def find(history, keyword):
        kw = normalize(keyword)
        return [m for m in history if kw in normalize(m["text"])]

class Stats:
    @staticmethod
    def render(history):
        users = [m for m in history if m["role"] == "user"]
        words = sum(len(tokenize(m["text"])) for m in users)
        return (f"Ուղերձներ՝ {len(history)}\n"
                f"Ձեր ուղերձները՝ {len(users)}\n"
                f"Բառեր՝ {words}\n"
                f"Առաջին՝ {datetime.datetime.fromtimestamp(history[0]['time']):%Y-%m-%d if history else '-'}")

