class Color:
    """Գույներ՝ եթե տերմինալը չի աջակցում՝ ավտոմատ անջատվում են"""

    ENABLED = True

    @classmethod
    def disable_if_no_support(cls):
        if os.environ.get("TERM", "") == "" and os.name != "nt":
            cls.ENABLED = False

    @classmethod
    def wrap(cls, code: str, text: str) -> str:
        if not cls.ENABLED:
            return text
        return f"\033[{code}m{text}\033[0m"

    @classmethod
    def red(cls, t): return cls.wrap("91", t)
    @classmethod
    def green(cls, t): return cls.wrap("92", t)
    @classmethod
    def yellow(cls, t): return cls.wrap("93", t)
    @classmethod
    def blue(cls, t): return cls.wrap("94", t)
    @classmethod
    def magenta(cls, t): return cls.wrap("95", t)
    @classmethod
    def cyan(cls, t): return cls.wrap("96", t)
    @classmethod
    def white(cls, t): return cls.wrap("97", t)
    @classmethod
    def dim(cls, t): return cls.wrap("90", t)
    @classmethod
    def bold(cls, t): return cls.wrap("1", t)

Color.disable_if_no_support()

