        m2 = re.search(r"([\d.,]+)\s*(ցելսիուս|ֆարենհայթ|kelvin|ց|կ|ֆ)(?:(?:\s*(?:փոխարկիր|դարձրու|հավասար է?))?[^Ա-Ֆա-ֆ]*?)(ցելսիուս|ֆարենհայթ|kelvin|ց|կ|ֆ)", text)
