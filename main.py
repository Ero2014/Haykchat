class Tools:
    CH = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789!@#$%^&*()-_=+"

    @classmethod
    def password(cls, n=12):
        while True:
            p = "".join(random.choice(cls.CH) for _ in range(max(6, n)))
            if (any(c.islower() for c in p) and any(c.isupper() for c in p) and any(c.isdigit() for c in p)):
                return p

    @classmethod
    def run(cls, text: str):
        low = normalize(text)
        if "գաղտնաբառ" in low or "password" in low:
            m = re.search(r"(\d+)", low)
            return f"[*P] {cls.password(int(m.group(1)) if m else 12)}"
        if "խառը թիվ" in low or "վիճակահանություն" in low:
            m = re.search(r"(\d+)\s*-\s*(\d+)", text)
            if m:
                a, b = sorted((int(m.group(1)), int(m.group(2))))
                return f"[*N] {random.randint(a, b)}"
            return f"[*N] {random.randint(1, 100)}"
        if "հակառակ" in low:
            body = re.sub(r"(?i)(հակառակ|դարձրու)", "", text).strip(" .,:;")
            if body:
                return f"[<-] {body[::-1]}"
        if "մեծատառ" in low:
            body = re.sub(r"(?i)(մեծատառ|դարձրու)", "", text).strip()
            if body:
                return f"[AA] {body.upper()}"
        if "փոքրատառ" in low:
            body = re.sub(r"(?i)(փոքրատառ|դարձրու)", "", text).strip()
            if body:
                return f"[aa] {body.lower()}"
        if re.search(r"\d+\s*%", text) or "տոկոս" in low:
            m = re.search(r"(\d+(?:[.,]\d+)?)\s*%\s*(?:-ից|ի)?\s*(\d+(?:[.,]\d+)?)", text)
            if m:
                p, v = float(m.group(1).replace(",", ".")), float(m.group(2).replace(",", "."))
                return f"[%] {p}% {v}-ից = {round(v * p / 100, 4)}"
        return None

