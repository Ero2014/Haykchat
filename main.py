class MathE:
    NAMES = {"sqrt": math.sqrt, "sin": math.sin, "cos": math.cos, "tan": math.tan,
             "log": math.log, "log10": math.log10, "log2": math.log2, "exp": math.exp,
             "abs": abs, "round": round, "pi": math.pi, "e": math.e, "pow": pow,
             "factorial": math.factorial, "floor": math.floor, "ceil": math.ceil,
             "gcd": math.gcd, "lcm": math.lcm, "degrees": math.degrees, "radians": math.radians}

    @classmethod
    def solve(cls, text: str):
        expr = re.search(r"[-0-9.,\s()+\-*/×÷^√a-zA-Z_]{3,}", text)
        if not expr:
            return None
        e = expr.group(0).strip()
        if not re.search(r"\d", e):
            return None
        try:
            e2 = e.replace("×", "*").replace("÷", "/").replace("^", "**").replace("√", "sqrt").replace("π", "pi")
            e2 = re.sub(r"[^\d\s+\-*/().,a-zA-Z_]", "", e2)
            e2 = re.sub(r"(?<=\d),(?=\d)", ".", e2)
            tree = compile(e2, "<e>", "eval")
            for n in set(tree.co_names):
                if n not in cls.NAMES:
                    raise ValueError(n)
            r = eval(tree, {"__builtins__": {}}, dict(cls.NAMES))
            if isinstance(r, float) and r.is_integer():
                r = int(r)
            return f"[==] Հաշվարկ.\n{e} = {r}"
        except Exception:
            return None

