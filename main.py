class Bubble(Label):
    def __init__(self, text, is_user, **kw):
        super().__init__(
            text=text, size_hint_y=None, markup=True, padding=(14, 10),
            halign="right" if is_user else "left", valign="middle",
            color=(1, 1, 1, 1), font_size="17sp", **kw,
        )
        self.is_user = is_user
        self.bind(texture_size=self._on_size)
        self._draw()

    def _on_size(self, *a):
        self.size = (self.texture_size[0] + 30, self.texture_size[1] + 22)
        self._draw()

    def _draw(self):
        self.canvas.before.clear()
        with self.canvas.before:
            KColor(*(USER_BG if self.is_user else BOT_BG))
            self.rect = RoundedRectangle(pos=self.pos, size=self.size, radius=[14,])
        self.bind(pos=lambda *a: setattr(self.rect, "pos", self.pos),
                  size=lambda *a: setattr(self.rect, "size", self.size))


class HaykApp(App):
    def build(self):
        Window.fullscreen = True
        Window.clearcolor = BG
        self.brain = Brain()
        self.brain.history = Storage.read(HISTORY_FILE, [])

        root = BoxLayout(orientation="vertical", padding=8, spacing=6)

        header = BoxLayout(size_hint_y=None, height=54, padding=6, spacing=6)
        with header.canvas.before:
            KColor(*PANEL)
            self.hr = RoundedRectangle(pos=header.pos, size=header.size, radius=[10,])
        header.bind(pos=lambda *a: setattr(self.hr, "pos", header.pos),
                    size=lambda *a: setattr(self.hr, "size", header.size))
        header.add_widget(Label(text="[b]🇦🇲 Հայկական Chat GPT[/b]", markup=True,
                                color=TXT, font_size="19sp", size_hint_x=0.7))
        header.add_widget(Label(text="⦿ օնլայն", color=(0.4, 0.9, 0.5, 1),
                                font_size="14sp", size_hint_x=0.3))
        root.add_widget(header)

        self.chat_layout = BoxLayout(orientation="vertical", size_hint_y=None,
                                     spacing=8, padding=6)
        self.chat_layout.bind(minimum_height=self.chat_layout.setter("height"))
        scroll = ScrollView(do_scroll_x=False)
        scroll.add_widget(self.chat_layout)
        root.add_widget(scroll)

        row = BoxLayout(size_hint_y=None, height=64, spacing=8)
        self.inp = TextInput(
            hint_text="Գրեք Ձեր հարցը...", multiline=False,
            background_color=INPUT_BG, foreground_color=TXT,
            hint_text_color=DIM, cursor_color=TXT, padding=(14, 14), font_size="17sp",
        )
        self.inp.bind(on_text_validate=self.send)
        row.add_widget(self.inp)
        btn = Button(text="➤", size_hint_x=None, width=70,
                     background_color=(0.35, 0.55, 0.90, 1),
                     color=(1, 1, 1, 1), font_size="24sp", bold=True)
        btn.bind(on_release=self.send)
        row.add_widget(btn)
        root.add_widget(row)

        name = f", {self.brain.name}" if self.brain.name else ""
        self.add_msg(f"🤖 Բարև{name}! Ես պատրաստ եմ օգնել։\n"
                     "💡 Օրինակ՝ «ինչ է արհեստական բանականությունը»", False)
        return root

    def add_msg(self, text, is_user):
        b = Bubble(text, is_user, size_hint_x=0.85)
        b.pos_hint = {"right": 1} if is_user else {"left": 1}
        self.chat_layout.add_widget(b)

    def send(self, *a):
        text = self.inp.text.strip()
        if not text:
            return
        self.inp.text = ""
        self.add_msg(text, True)
        self.brain.history.append({"role": "user", "text": text, "time": time.time()})
        threading.Thread(target=self._think, args=(text,), daemon=True).start()

    def _think(self, text):
        time.sleep(0.4)
        ans = self.brain.reply(text)
        self.brain.history.append({"role": "assistant", "text": ans, "time": time.time()})
        Storage.write(HISTORY_FILE, self.brain.history[-300:])
        Clock.schedule_once(lambda dt: self.add_msg(ans, False))


if __name__ == "__main__":
    HaykApp().run()
