    @classmethod
    def run(cls, text: str):
        m = re.search(r"([\d.,]+)\s*(կմ|մ|սմ|մմ|մղոն|ֆուտ|դյույմ|կգ|գ|տոննա|ֆունտ|լիտր|մլ|գալոն)(?:(?:\s*(?:փոխարկիր|դարձրու|հավասար է?))?[^Ա-Ֆա-ֆ]*?)(կմ|մ|սմ|մմ|մղոն|ֆուտ|դյույմ|կգ|գ|տոննա|ֆունտ|լիտր|մլ|գալոն)", text)
        if m:
            v = float(m.group(1).replace(",", "."))
            f, t = cls.U.get(m.group(2)), cls.U.get(m.group(3))
