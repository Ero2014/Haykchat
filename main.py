class WordChain:
    """Բառաշղթա՝ նախագծի մեջ նոր տառով"""
    WORDS = ["ԱՐև", "ՎԱՐԴ", "ԴԱՐ", "ՐՈՊԵ", "ԷՋ", "ՇՈՒՆ", "ՆՈՐ", "ՐԱՆԳ", "ԿԱՏՈՒ", "ՈՒՂԵԳԻՐ",
             "ՐԵՏ", "ՏԱՂ", "ՂԵԿԱՎԱՐ", "ՐԱՊ", "ՊԱՏ", "ՏԱՆԻԿ", "ԿԱՐԳ", "ԳԻՐ", "ՐԱՇ", "ՇԱՂ",
             "ԱՂ", "ՂՈՒԶ", "ԶԱՆԳ", "ԳԱՀ", "ՀՈՒՅՍ", "ՍԱՐ", "ՐՈՒՆ", "ՆԱՄԱԿ", "ԿԱՐԻՒ", "ՒՈՒՐԽ"]

    def __init__(self):
        self.active = False
        self.last = None
        self.used = set()

    def start(self):
        self.active = True
        self.used = set()
        self.last = random.choice(self.WORDS)
        self.used.add(self.last)
        return f"[ՈՒ] Բառաշղթա սկսեցինք՝ «{self.last}»։ Գրեք բառ, որը սկսվում է «{self.last[-1]}» տառով։"

    def play(self, word: str):
        if not self.active:
            return None
        w = word.strip().upper()
        if not w:
            return None
        if not all(ch in ARM_UPPER for ch in w):
            return "[!] Միայն հայերեն տառերով։"
        need = self.last[-1]
        if w[0] != need:
            return f"[!] Պետք է սկսվի «{need}» տառով։"
        if w in self.used:
            return "[!] Այս բառն արդեն ասվել է։"
        self.used.add(w)
        self.last = w
        nxt = need if need in "ԱԵԸՈՕ" else self.last[-1]
        return f"[+] Լավ է! «{w}»։ Այժմ Ձեր հերթը՝ «{self.last[-1]}» տառով։"

