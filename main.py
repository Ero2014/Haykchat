class QuizGame:
    def __init__(self):
        self.active = False
        self.q = None
        self.score = 0
        self.asked = 0
        self.used = []

    def start(self):
        self.active = True
        self.score = 0
        self.asked = 0
        self.used = []
        return self.next_q()

    def next_q(self):
        rest = [q for q in QUIZ if q[0] not in self.used]
        if not rest:
            self.active = False
            return "Վիկտորինան ավարտվեց։ Գրեք «վիկտորինա»՝ նորից։"
        self.q = random.choice(rest)
        self.used.append(self.q[0])
        opts = "\n".join(f"  {i+1}) {o}" for i, o in enumerate(self.q[2]))
        return f"[?] {self.q[0]}\n{opts}\n(գրեք համարը կամ պատասխանը)"

    def check(self, ans: str):
        if not self.active or not self.q:
            return None
        correct = normalize(self.q[1])
        guess = normalize(ans)
        nums = {"1": 0, "2": 1, "3": 2, "4": 3, "մեկ": 0, "երկու": 1, "երեք": 2, "չորս": 3}
        ok = False
        if guess in nums and nums[guess] < len(self.q[2]):
            ok = self.q[2][nums[guess]] == self.q[1]
        else:
            ok = correct in guess or guess in correct
        self.asked += 1
        head = ""
        if ok:
            self.score += 1
            head = f"[+] Ճիշտ է! ({self.score}/{self.asked})\n"
        else:
            head = f"[x] Սխալ։ Ճիշտը՝ «{self.q[1]}» ({self.score}/{self.asked})\n"
        return head + self.next_q()

