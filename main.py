class RPSGame:
    """Քար-Թուղթ-Խփանիչ"""
    CHOICES = {"քար": "rock", "թուղթ": "paper", "խփան": "scissors",
               "rock": "rock", "paper": "paper", "scissors": "scissors"}
    NAMES = {"rock": "ՔԱՐ", "paper": "ԹՈՒՂԹ", "scissors": "ԽՓԱՆ"}

    @classmethod
    def play(cls, user_raw: str):
        u = cls.CHOICES.get(normalize(user_raw))
        if not u:
            return None
        c = random.choice(["rock", "paper", "scissors"])
        if u == c:
            res = "Ոչ-ոքի!"
        elif (u == "rock" and c == "scissors") or (u == "paper" and c == "rock") or (u == "scissors" and c == "paper"):
            res = "Դուք հաղթեցիք!"
        else:
            res = "Ես հաղթեցի!"
        return f"Դուք՝ {cls.NAMES[u]} / Ես՝ {cls.NAMES[c]}\n{res}"

