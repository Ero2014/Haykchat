def brain_extended(self, text: str):
    """Լրացուցիչ հնարավորություններ՝ Brain-ի համար"""
    low = normalize(text)

    # Այբուբեն սովորել
    if "այբուբեն" in low and any(k in low for k in ["ցույց", "սովորիր", "բոլոր", "տուր"]):
        return AlphabetTeacher.all()
    if "համարիր" in low or "թվիր" in low:
        m = re.search(r"\d+", text)
        if m:
            n = int(m.group(0))
            return f"[#] {n} = {NumberTeacher.to_arm(n)}"
    # Քար-թուղթ-խփան
    rps = RPSGame.play(text)
    if rps:
        return f"[x/o] {rps}"
    # Ամսաթիվ ձևակերպված
    if "ամսաթիվ" in low or "որը օր" in low:
        return DateInfo.today()
    return None

Brain.extended = brain_extended

_orig_reply = Brain.reply
def _reply2(self, text: str):
    r = self.extended(text)
    if r:
        return r
    return _orig_reply(self, text)
Brain.reply = _reply2

