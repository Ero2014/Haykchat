        if "փաստ" in low:
            return random.choice(FACTS)
        if "քաղվածք" in low or "մեջբերում" in low:
            return random.choice(QUOTES)
        if "հայտնի" in low:
            return random.choice(FACTS)

        # Ժամանակ
        if "ժամ" in low and ("քանի" in low or "որը" in low):
            return f"[*T] Հիմա՝ {datetime.datetime.now():%H:%M}"
        if "ամսաթիվ" in low or ("օր" in low and "քանի" in low):
            return f"[*D] {datetime.datetime.now():%Y-%m-%d}"

        # Ճանաչում
        ts = token_set(text)
        best, entry = 0.0, None
        for e in KB:
            for trg in e["t"]:
                s = jaccard(set(trg), ts)
                if set(trg).issubset(ts):
                    s += 0.3
                if s > best:
                    best, entry = s, e
