class Hangman:
    WORDS = ["ԱՐԵՎ", "ԼՈՒՍԻՆ", "ԳԻՐՔ", "ՁՈՒԿ", "ԾԱՂԻԿ", "ՇՈՒՆ", "ՔԱՂԱՔ",
             "ՍԱՐ", "ՑԱՆԿ", "ՊԱՏՄՈՒԹՅՈՒՆ", "ԳԱՐՈՒՆ", "ԱՇՈՒՆ"]

    def __init__(self):
        self.active = False
        self.word = ""
        self.guessed = set()
        self.lives = 6

    def start(self):
        self.active = True
        self.word = random.choice(self.WORDS)
        self.guessed = set()
        self.lives = 6
        return self.render()

    def render(self):
        disp = " ".join(ch if ch in self.guessed else "_" for ch in self.word)
        tried = " ".join(sorted(self.guessed - set(self.word)))
        return (f"[{disp}]\n"
                f"Կյանք՝ {self.lives} | Ասված՝ {tried or '-'}\n"
                "Գրեք տառը։")

    def guess_letter(self, ch: str):
        if not self.active:
            return None
        ch = ch.upper()
        if len(ch) != 1 or ch not in ARM_UPPER:
            return "[!] Միայն մեկ հայերեն տառ։"
        if ch in self.guessed:
            return "[!] Այս տառն արդեն ասել եք։"
        self.guessed.add(ch)
        if ch in self.word:
            if all(c in self.guessed for c in self.word):
                self.active = False
                return f"🎉 Հաղթեցիք! Խոսքը՝ «{self.word}»։"
            return "[+] Կա՛ էդ տառը!\n" + self.render()
        self.lives -= 1
        if self.lives <= 0:
            self.active = False
            return f"💀 Պարտվեցիք։ Խոսքը՝ «{self.word}»։"
        return f"[-] Չկա։\n" + self.render()

